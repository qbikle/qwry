// ---- the seed --------------------------------------------------------------

export interface E2Seed {
  /** the tab the state's act runs against */
  activeTabId: string;
  tabs: Tab[];
  /** useResults.byTab */
  results: Record<string, { statements: StatementResult[]; sql: string; totalMs: number }>;
  /** the three staged edits `e2-table-staged` keeps through the gesture */
  pending: { row: number; col: number; value: string; original: string }[];
  canvases: Record<string, CanvasMeta[]>;
  docs: Record<string, CanvasDoc>;
  /** the connection answers a probe (R6's dead state is the one that does not) */
  alive: boolean;
}

const tab = (over: Partial<Tab> & Pick<Tab, "id" | "name" | "kind" | "position">): Tab => ({
  sql: "",
  saved_id: null,
  table: null,
  canvas_id: null,
  profile_id: E2_PROFILE_ID,
  ...over,
});

export function e2Seed(state: E2State): E2Seed {
  const tabs: Tab[] = [
    tab({ id: E2_TABLE_TAB, name: "users", kind: "table", position: 0, table: E2_USERS }),
    tab({ id: E2_QUERY_TAB, name: "new qwry", kind: "query", position: 1, sql: E2_READ_SQL }),
    tab({
      id: E2_CANVAS_TAB,
      name: "Canvas 1",
      kind: "canvas",
      position: 2,
      canvas_id: E2_CANVAS_ID,
    }),
  ];
  const wrote = state === "e2-query-wrote";
  const query = wrote ? E2_WRITE_SQL : E2_READ_SQL;
  if (wrote) tabs[1].sql = E2_WRITE_SQL;
  const activeTabId =
    state === "e2-query" || wrote
      ? E2_QUERY_TAB
      : state === "e2-canvas"
        ? E2_CANVAS_TAB
        : E2_TABLE_TAB;
  return {
    activeTabId,
    tabs,
    results: {
      [E2_TABLE_TAB]: {
        statements: [statement(e2BrowseSql())],
        sql: e2BrowseSql(),
        totalMs: 41.2,
      },
      [E2_QUERY_TAB]: {
        statements: [
          wrote
            ? statement(E2_WRITE_SQL, { columns: [], rows: [], affected: 1, ms: 12.6 })
            : statement(E2_READ_SQL),
        ],
        sql: query,
        totalMs: wrote ? 12.6 : 41.2,
      },
    },
    pending:
      state === "e2-table-staged"
        ? [
            { row: 1, col: 2, value: "Grace B. Hopper", original: "Grace Hopper" },
            { row: 5, col: 3, value: "true", original: "false" },
            { row: 8, col: 1, value: "tim@w3.org", original: "tim.berners.lee@example.com" },
          ]
        : [],
    canvases: { [E2_PROFILE_ID]: [e2CanvasMeta] },
    docs: { [E2_CANVAS_ID]: e2Doc },
    alive: state !== "e2-dead",
  };
}

/** The one thing a seed cannot hold: the grid's selection. It is the Grid
 * component's own React state with no store door (useSelection), so the
 * sketch's selected row is reached the way the canvas fixtures reach a menu,
 * by pressing the cell the product would be pressed on. Run BEFORE the act,
 * because a selection is part of the window the gesture arrives at, not part
 * of the gesture (R4: the selected row is what must survive). */
export async function e2AfterMount(state: E2State): Promise<void> {
  if (state === "e2-canvas" || state === "e2-query-wrote") return;
  const cell = document.querySelector<HTMLElement>(
    `.vgrid-cell[data-r="${E2_SEL_ROW}"][data-c="1"]`,
  );
  cell?.dispatchEvent(new MouseEvent("mousedown", { bubbles: true, button: 0 }));
  window.dispatchEvent(new MouseEvent("mouseup", { bubbles: true }));
  await new Promise<void>((r) => requestAnimationFrame(() => r()));
}
