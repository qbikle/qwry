/** what a canvas widget's refetch reads back, by the SQL it sends.
 * `refreshWidget` goes through `execute`, and a shim that answered it with no
 * columns would draw the FAILED refetch — the widget's own error strip — in
 * the frame that exists to show the landing. `lat` is the sketch's own
 * 800 + 140 per widget, which staggers the landings the way the band's front
 * already staggers the starts */
export interface E2WidgetResult {
  /** the block the SQL belongs to, so the shim's log can say WHICH widget a
   * refetch was for and a timing assertion can name it */
  id: string;
  columns: ColumnMeta[];
  rows: (string | null)[][];
  lat: number;
  ms: number;
}

export function e2WidgetResult(sql: string): E2WidgetResult | null {
  const results = e2Doc.blocks.filter((b): b is ResultBlock => b.kind === "result");
  const i = results.findIndex((b) => b.sql === sql);
  const block = results[i];
  if (!block) return null;
  return {
    id: block.id,
    columns: (block.columns ?? []).map((name, c) => ({
      name,
      type_oid: 25,
      table_oid: 0,
      attnum: c + 1,
    })),
    rows: block.rows.map((r) => [...r]),
    lat: 800 + i * 140,
    ms: block.ms ?? 0,
  };
}

