// Refresh fixtures (E2, the locked sketch qwry-agent-lab/docs/refresh-sketch-e2.html).
// The refresh harness is the FIRST to frame the whole window rather than one
// card's face: ⌘R and ⇧⌘R are shell-wide acts, and a sweep that crosses the
// sidebar, the main card and the inspector cannot be evidenced inside any one
// of them. So these seeds fill every store the shell reads (connections, tabs,
// schema, browser, results, edits, inspector, side pane, canvas) and
// RefreshHarness composes the real `.v2-shell` around them.
//
//   e2-table         a browse tab on public.users, 14 rows, the 4th selected
//                    in the inspector, the sketch's `hard-ok` scenario
//   e2-table-staged  the same tab with 3 staged edits: its main body must NOT
//                    refetch (R4), so the frame's evidence is the rows still
//                    standing under a sweep that crossed them
//   e2-query         a read-only SELECT with its rows: every executed head is
//                    read-only, so the tab reruns
//   e2-query-wrote   the same tab after an UPDATE: `OK · 1 row affected`, the
//                    rows stay and the status bar says why (R4)
//   e2-canvas        two result widgets, a note, a third result widget: the
//                    widgets refetch in the order the sweep's front reaches
//                    them and the note never does
//   e2-dead          session_probe answers false and connect rejects, so the
//                    sweep plays over surfaces that never cycle (R6)
//
// The row data is the sketch's own, generated by the sketch's own expressions
// rather than transcribed, and the browse SQL comes from the product's
// `browseSql`, so `executedSql` is exactly what a refresh run re-executes.

